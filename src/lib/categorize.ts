const norm = (s: string) => s.replace(/\s+/g, '').toLowerCase()

/** 글(이름·상품명·가게·플랫폼을 이은 것)에 맞는 분류 이름들, 규칙 순서대로 */
export function suggestCategoryNames(text: string): string[] {
  const t = norm(text)
  if (!t) return []
  return RULES.filter(([, words]) => words.some((w) => t.includes(w))).map(([name]) => name)
}

/** 가구에 있는 분류 중 글에 맞는 첫 번째. 없으면 null. 수입은 제안하지 않는다 */
export function suggestCategory(text: string, categories: Category[], type: TxType = 'expense'): Category | null {
  if (type !== 'expense') return null
  for (const name of suggestCategoryNames(text)) {
    const c = categories.find((x) => x.type === 'expense' && x.name === name && !x.archived)
    if (c) return c
  }
  return null
}

/** 매장 결제의 가게 이름: 법인 표기와 뒤에 붙은 지점 이름을 뺀다 ('(주)신세계까사' → '신세계까사', '씨유 분당상록마을점' → '씨유') */
export function normMerchant(title: string): string {
  const s = title.replace(/\(주\)|㈜|주식회사|\(유\)/g, '').replace(/\s+/g, ' ').trim()
  const parts = s.split(' ')
  if (parts.length > 1 && /점$/.test(parts[parts.length - 1])) parts.pop()
  return parts.join(' ').slice(0, 30)
}
