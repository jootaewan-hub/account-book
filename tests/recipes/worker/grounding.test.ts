describe('hasDuration', () => {
  it.each<[string, number]>([
    ['센 불에서 3분 정도 볶아요', 180],
    ['30초만 더', 30],
    ['1분 30초', 90],
    ['1분 반', 90],
    ['한 시간 반', 5400],
    ['삼 분 뒤에', 180],
  ])('%s → %d초 있음', (text, seconds) => {
    expect(hasDuration(text, seconds)).toBe(true)
  })

  it.each<[string, number]>([
    ['3~4분', 180],
    ['2인분', 120],
    ['3분', 30],
    ['넣어 두세요', 180],
    ['3,4분', 180],
    ['3,4분', 240],
    ['3에서 4분', 240],
  ])('%s → %d초 없음', (text, seconds) => {
    expect(hasDuration(text, seconds)).toBe(false)
  })
})

describe('hasServings', () => {
  it('인분·인·명은 단위가 있어야 하고 범위는 안 됨', () => {
    expect(hasServings('[재료] 2인분', 2)).toBe(true)
    expect(hasServings('두 사람이 먹기 좋아요', 2)).toBe(true)
    expect(hasServings('3인 기준', 3)).toBe(true)
    expect(hasServings('달걀 2개', 2)).toBe(false)
    expect(hasServings('4~5인분', 4)).toBe(false)
  })
})
