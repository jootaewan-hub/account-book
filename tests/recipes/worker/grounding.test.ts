describe('canonUnit', () => {
  it('T·t는 대소문자를 지켜 큰술·작은술로, 스푼·숟가락·밥숟가락은 서로 다르게', () => {
    expect(canonUnit('T')).toBe('큰술')
    expect(canonUnit('t')).toBe('작은술')
    expect(canonUnit('큰술')).toBe('큰술')
    expect(canonUnit('그램')).toBe('g')
    expect(canonUnit('mL')).toBe('ml')
    expect(new Set([canonUnit('스푼'), canonUnit('숟가락'), canonUnit('밥숟가락'), canonUnit('큰술')]).size).toBe(4)
    expect(canonUnit('주먹')).toBe('주먹')
  })
})

